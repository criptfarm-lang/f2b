"""Тесты нормализации номера перед отправкой в Wazzup.

План: plans/2026-08-04-нормализация-номера-рассылка-фишки.md (репо «второй мозг»).
Все входные значения — реальные, из скана поля «Max» контрагентов МойСклад 04.08.2026.

Запуск: python3 -m pytest test_notifier_phone.py -q
"""
import pytest

from notifier import _normalize_phone


@pytest.mark.parametrize("raw,expected", [
    # Грязный формат — то, из-за чего падала рассылка
    ("8-920-315-54-51", "79203155451"),      # ООО «РЕСТО», заказ 03358
    ("+7 (965) 229-73-74", "79652297374"),   # ООО «ДАЧА», заказ 03363
    ("7991121 66 69", "79911216669"),        # ООО «ШЕФС»
    ("+7 912 182-76-93", "79121827693"),     # ООО «СЕВЕР»
    ("7 915 978-56-52", "79159785652"),      # ООО «ХОРЕКА ПРОФИ»
    # Восьмёрка и плюс
    ("89104484950", "79104484950"),          # ООО «ИТАЛЬЯНКА»
    ("+79268640584", "79268640584"),         # ООО «ЛИЛУ МА»
    # Без кода страны
    ("9203155451", "79203155451"),
    # Уже канонический — не меняем
    ("79263338420", "79263338420"),          # ИП Ван Виктор Валериевич
])
def test_phone_normalized(raw, expected):
    assert _normalize_phone(raw) == expected


@pytest.mark.parametrize("raw", [
    "144978695",    # MAX user-id (ООО «ПФП») — короче 10 цифр, не трогаем
    "824409723",    # MAX/Telegram id — 9 цифр
    "6207868491",   # Telegram numeric user_id — 10 цифр, но не с девятки
    "@hasunchik",   # Telegram username (ООО «ТРИО»)
    "",             # пусто
    "нет",          # мусор
])
def test_value_untouched(raw):
    assert _normalize_phone(raw) == raw


def test_whitespace_stripped():
    assert _normalize_phone("  79263338420  ") == "79263338420"

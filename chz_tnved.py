def group_by_tnved(code: str, *, net_weight_g: float | None = None,
                   hermetic_sterilized: bool | None = None,
                   breadcrumbs: bool = False, milk_fat_replaced: bool = False,
                   frozen: bool | None = None) -> tuple[str, str]:
    """(ключ группы, пояснение). Ключ 'none' — по коду не маркируется."""
    digits = re.sub(r"\D", "", code or "")
    if len(digits) < 4:
        return "unknown", "код ТН ВЭД не определён"
    if breadcrumbs:
        return "none", f"ТН ВЭД {digits} – панировочные сухари исключены (ПП 1682 п. 3)"
    notes = []
    for key, codes, excl, cond in _TABLE:
        if not any(digits.startswith(c) for c in codes):
            continue
        if any(digits.startswith(c) for c in excl):
            notes.append(f"{key}: код в исключениях")
            continue
        if "weight30" in cond and net_weight_g is not None and net_weight_g <= 30:
            notes.append(f"{key}: масса ≤ 30 г")
            continue
        if "weight30_sauce" in cond and digits.startswith("2103") \
                and net_weight_g is not None and net_weight_g <= 30:
            notes.append("соус ≤ 30 г")
            continue
        if "hermetic" in cond and hermetic_sterilized is False:
            notes.append("не консервы: не стерилизован в герметичной таре")
            continue
        if key == "dairy" and milk_fat_replaced:
            notes.append("молочный жир заменён – не молочка")
            continue
        if key == "frozen" and frozen is False:
            notes.append("эксперимент 1823 – только заморозка и полуфабрикаты")
            continue
        why = f"ТН ВЭД {digits}"
        if key == "canned" and hermetic_sterilized is None:
            why += ", консервы – если тара герметичная и продукт стерилизован"
        return key, why + (f" ({'; '.join(notes)})" if notes else "")
    return "none", f"ТН ВЭД {digits} – нет в перечнях" + (f" ({'; '.join(notes)})" if notes else "")
